# Here is a simple function without arguments.
def greet():
    print("Hello, welcome to Python!")


# Here is a function with one argument.
def greet_person(name):
    print("Hello,", name)


# Here is a function with two arguments.
def add_numbers(a, b):
    print(a + b)


# Here is an example of calling the functions.
greet()
greet_person("Gulim")
add_numbers(10, 5)
