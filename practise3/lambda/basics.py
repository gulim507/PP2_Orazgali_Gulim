# Here is a simple lambda function that adds two numbers.
add = lambda a, b: a + b


# Here is a lambda function that calculates a square.
square = lambda number: number * number


# Here is a lambda function that checks if a number is even.
is_even = lambda number: number % 2 == 0


# Here is an example of using the first lambda function.
print("Sum:", add(5, 3))

# Here is an example of using the second lambda function.
print("Square:", square(6))

# Here is an example of using the third lambda function.
print("Is even:", is_even(10))